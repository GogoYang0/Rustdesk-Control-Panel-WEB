function localizeTokens(text: string, lang: SpaceLang): string {
  let next = text
  for (const [label, translated] of Object.entries(LABELS[lang])) {
    next = next.replace(new RegExp(`${label}\\s*#`, 'g'), `${translated} #`)
  }
  const units = UNITS[lang]
  for (const [unit, [single, plural]] of Object.entries(units)) {
    next = next.replace(new RegExp(`(\\d+)\\s*${unit}`, 'g'), (_all, count: string) => {
      const form = lang === 'en' || lang === 'ru' ? (count === '1' ? single : plural) : single
      return lang === 'ja' || lang === 'zh-TW' ? `${count}${form}` : `${count} ${form}`
    })
  }
  if (lang === 'en') next = next.replace(/第 (\d+) \/ (\d+) 页/g, 'page $1 of $2')
  if (lang === 'ru') next = next.replace(/第 (\d+) \/ (\d+) 页/g, 'стр. $1 из $2')
  if (lang === 'ja') next = next.replace(/第 (\d+) \/ (\d+) 页/g, '$1/$2ページ')
  if (lang === 'zh-TW') next = next.replace(/第 (\d+) \/ (\d+) 页/g, '第 $1 / $2 頁')
  return next
}
